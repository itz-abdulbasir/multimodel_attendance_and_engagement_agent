class CodeExecutor:
    """
    Executes generated code files in a controlled environment to output analytics.
    """

    @staticmethod
    def execute_script(filepath: str) -> Dict[str, Any]:
        """Executes a Python script and captures stdout/stderr."""
        if not os.path.exists(filepath):
            return {"success": False, "error": f"File not found: {filepath}", "output": ""}

        with open(filepath, "r", encoding="utf-8") as f:
            code = f.read()

        stdout_capture = io.StringIO()
        stderr_capture = io.StringIO()
        success = True
        error_msg = None

        with contextlib.redirect_stdout(stdout_capture), contextlib.redirect_stderr(stderr_capture):
            try:
                # Execute in local sandbox
                exec_globals = {"__name__": "__main__"}
                exec(code, exec_globals)
            except Exception as e:
                success = False
                error_msg = str(e)

        output = stdout_capture.getvalue()
        err_output = stderr_capture.getvalue()

        return {
            "success": success,
            "output": output or ("Script executed successfully (no stdout)" if success else ""),
            "stderr": err_output or error_msg,
            "filename": os.path.basename(filepath),
            "execution_time": time.time()
        }
